"""Translate FlClash's declarative glyph catalogue, retaining all path coordinates.

The bundled reference is read-only. Run with --check in CI to detect catalogue drift.
"""
from pathlib import Path
import re
import sys
import json

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'tools/ios27/reference/app_glyphs.dart'
TARGET = ROOT / 'liquidglass-ios27/src/main/java/dev/liquidglass27/glass/GlassGlyphs.kt'
NAMES = {'Glyph': 'GlassGlyph', 'GlyphVertex': 'GlassGlyphVertex', 'Offset': 'Offset',
         **{'Glyph' + n: 'GlassGlyphShapes.' + f for n, f in
            [('Box', 'box'), ('Circle', 'circle'), ('Oval', 'oval'), ('Arc', 'arc'),
             ('Link', 'link'), ('Path', 'svg'), ('Polyline', 'polyline')]}}


def translate(expr):
    expr = re.sub(r'//[^\n]*', '', expr)
    tokens = re.findall(r"'(?:\\.|[^'\\])*'|\d+(?:\.\d+)?|[A-Za-z_]\w*|[^\s]", expr)
    at = 0

    def expression():
        nonlocal at
        result = atom()
        while at < len(tokens) and tokens[at] in ('+', '-', '*', '/'):
            op = tokens[at]; at += 1
            result += ' ' + op + ' ' + atom()
        return result

    def atom():
        nonlocal at
        token = tokens[at]; at += 1
        if token == '-': return '-' + atom()
        if token.startswith("'"):
            parts = [token[1:-1]]
            while at < len(tokens) and tokens[at].startswith("'"):
                parts.append(tokens[at][1:-1]); at += 1
            return json.dumps(''.join(parts))
        if re.fullmatch(r'\d+(?:\.\d+)?', token): return token + 'f'
        if token == '[':
            values = sequence(']')
            return 'listOf(' + ', '.join(values) + ')'
        if token == 'math':
            assert tokens[at:at+2] == ['.', 'pi']; at += 2
            return 'kotlin.math.PI.toFloat()'
        if token == 'GlyphRole':
            assert tokens[at] == '.'; at += 1
            role = tokens[at]; at += 1
            return 'GlassGlyphRole.' + role.capitalize()
        if at < len(tokens) and tokens[at] == '(':
            at += 1
            values = sequence(')')
            if token == 'GlyphPolyline':
                assert values[0].startswith('listOf(')
                values[0] = '*arrayOf(' + values[0][7:]
            return NAMES[token] + '(' + ', '.join(values) + ')'
        assert token in ('true', 'false', 'requests'), token
        return token

    def sequence(end):
        nonlocal at
        values = []
        while tokens[at] != end:
            if at + 1 < len(tokens) and tokens[at + 1] == ':':
                name = tokens[at]; at += 2
                values.append(name + ' = ' + expression())
            else: values.append(expression())
            if tokens[at] == ',': at += 1
            else: assert tokens[at] == end, tokens[at:at+5]
        at += 1
        return values

    result = expression()
    assert at == len(tokens), tokens[at:]
    return result


entries = re.findall(r'  static const (\w+) = (.*?);',
                     SOURCE.read_text(encoding='utf-8').split('  static Glyph sidebar')[0], re.S)
body = '\n'.join('    val ' + name + ' by lazy { ' + translate(value) + ' }' for name, value in entries)
catalogue = ',\n'.join('        "' + name + '" to ' + name for name, _ in entries)
output = '''// Generated by tools/generate_glass_glyphs.py from FlClash (GPL-3.0).
package dev.liquidglass27.glass

import androidx.compose.ui.geometry.Offset

object GlassGlyphs {
''' + body + '''

    val all: Map<String, GlassGlyph> by lazy { linkedMapOf(
''' + catalogue + '''
    ) }

    fun sidebar(progress: Float) = glassSidebarGlyph(progress)
    fun playPause(progress: Float) = glassPlayPauseGlyph(progress)
    fun backFor(apple: Boolean = false) = if (apple) chevronBack else arrowBack

    internal fun forSymbol(symbol: String): GlassGlyph? = when (symbol) {
        "⌂" -> dashboard
        "≋" -> proxies
        "◈" -> profiles
        "⚙" -> settings
        "⌕" -> search
        "ⓘ" -> info
        "☼", "☾" -> sun
        "≡" -> appsList
        "↺" -> reset
        "⇄" -> swap
        "↗" -> openExternal
        "＋", "+" -> add
        "•••" -> more
        "↩" -> arrowBack
        "◉", "◌", "◇" -> liquidGlass
        "◫", "▦" -> layers
        "›" -> chevronForward
        "✧" -> sparkle
        "⌁" -> motion
        "•" -> bullet
        else -> null
    }
    private val bullet by lazy { GlassGlyph(listOf(GlassGlyphShapes.circle(12f, 12f, 2f, solid = true))) }
}
'''
if '--check' in sys.argv:
    assert TARGET.read_text(encoding='utf-8') == output, 'Regenerate GlassGlyphs.kt'
else:
    TARGET.write_text(output, encoding='utf-8', newline='\n')
print(f'{len(entries)} glyphs: ' + ('verified' if '--check' in sys.argv else 'generated'))
