// Projects ONLY page/list/typography tokens. Glass material tokens are not consumed.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tokenRoot = path.join(root, 'vendor/ios27-design-system/packages/tokens/src');
const names = ['colors', 'spacing', 'typography'];
const data = Object.fromEntries(names.map(n => [n, JSON.parse(fs.readFileSync(path.join(tokenRoot, `${n}.json`), 'utf8'))]));
const { colors: c, spacing: s, typography: t } = data;
const localLayout = JSON.parse(fs.readFileSync(path.join(root, 'docs/figma-local-measurements.json'), 'utf8'));
const measuredNode = id => {
    const node = localLayout.nodes.find(n => n.id === id);
    if (!node) throw new Error(`Missing local Figma node ${id}`);
    return node;
};
const color = v => `Color(0xFF${(typeof v === 'string' ? v : v.hex).slice(1).toUpperCase()})`;
const f = v => `${Number(v)}f`;
const rgba = v => `${color(v)}.copy(alpha = ${f(v.a ?? 1)})`;
const cap = v => v[0].toUpperCase() + v.slice(1);
const localColor = (name, mode) => {
    const v = localLayout.colors[name]?.[mode];
    if (!v) throw new Error(`Missing local color ${name}/${mode}`);
    const hex = [v.r, v.g, v.b].map(x => Math.round(x * 255).toString(16).padStart(2, '0')).join('');
    return `Color(0xFF${hex.toUpperCase()}).copy(alpha = ${f(Number(v.a.toFixed(4)))})`;
};
const lines = [
    '// GENERATED by tools/generate-ios27-tokens.mjs. No glass component parameters.',
    `// Local Untitled.fig canvas SHA256 ${localLayout.canvasSha256}`,
    ...names.map(n => `// ${n}.json SHA256 ${createHash('sha256').update(fs.readFileSync(path.join(tokenRoot, `${n}.json`))).digest('hex')}`),
    'package dev.liquidglass.ios27', '',
    'import androidx.compose.ui.graphics.Color',
    'import androidx.compose.ui.text.TextStyle',
    'import androidx.compose.ui.text.font.FontFamily',
    'import androidx.compose.ui.text.font.FontWeight',
    'import androidx.compose.ui.unit.sp', '',
    'object Ios27Tokens {',
];
const dimensions = {
    ContentMargin: s.contentMargin.iphone.horizontal,
    ReadableWidth: s.contentMargin.readableWidth.max,
    RowHeight: s.components.listRow.heightRegular,
    TallRowHeight: s.components.listRow.heightTall,
    RowPadding: s.components.listRow.paddingHorizontal,
    RowVerticalPadding: s.components.listRow.paddingVertical,
    SeparatorInset: s.components.listRow.separatorInset,
    SeparatorHeight: s.components.listRow.separatorHeight,
    // Figma's 1pt separator is rendered at the reference capture scale as a
    // visibly stronger 2dp Android line. Keep this centralized for reuse.
    SeparatorRenderHeight: s.components.listRow.separatorHeight * 2,
    SectionHeaderHeight: s.components.listRow.sectionHeaderNested,
    ProminentHeaderHeight: s.components.listRow.sectionHeaderProminent,
    ExtraProminentHeaderHeight: s.components.listRow.sectionHeaderExtraProminent,
    SectionFooterHeight: s.components.listRow.footerHeight,
    SectionHeaderPadding: s.components.listRow.sectionHeaderPaddingVertical,
    // Direct measurements from the user-supplied Examples/Slider page.
    GroupRadius: measuredNode('1:774').cornerRadius,
    GroupGap: measuredNode('1:773').layout.stackSpacing,
    CompactHeaderHeight: measuredNode('1:782').size.y,
    LeadingGap: s.inset.md,
    TrailingGap: s.inset.xs,
    // Image-slot dimensions are recorded in spacing.json radius observations.
    IconSize: 30,
    IconRadius: 7,
    TallIconSize: 44,
    TallIconRadius: 11,
};
for (const [key, value] of Object.entries(dimensions)) lines.push(`    const val ${key} = ${f(value)}`);
for (const mode of ['light', 'dark']) {
    const suffix = cap(mode);
    lines.push(`    val Page${suffix} = ${localColor('Backgrounds (Grouped)/Primary', mode)}`);
    lines.push(`    val Group${suffix} = ${localColor('Backgrounds/Primary', mode)}`);
    // General grouped pages are distinct from the local slider example's primary fill.
    lines.push(`    val GroupedSurface${suffix} = ${color(c.backgroundsGrouped.secondary[mode])}`);
    lines.push(`    val Label${suffix} = ${localColor('Labels/Primary', mode)}`);
    lines.push(`    val SecondaryLabel${suffix} = ${localColor('Labels/Secondary', mode)}`);
    // Vibrant separator resolved on this reference's opaque white/black group.
    lines.push(`    val Separator${suffix} = ${localColor('Separators/Vibrant', mode)}`);
    lines.push(`    val Pressed${suffix} = ${localColor('Fills/Tertiary', mode)}`);
    for (const accent of ['blue', 'green', 'orange', 'red']) {
        lines.push(`    val ${cap(accent)}${suffix} = ${accent === 'blue' ? localColor('Accents/Blue', mode) : color(c.accents[accent][mode])}`);
    }
}
lines.push('    object Type {');
for (const [name, v] of Object.entries(t.styles)) {
    const weight = v.regular === 'Semibold' ? 'SemiBold' : 'Normal';
    lines.push(`        val ${cap(name)} = TextStyle(fontFamily = FontFamily.SansSerif, fontSize = ${v.fontSize}.sp, lineHeight = ${v.lineHeight}.sp, letterSpacing = ${v.letterSpacing}.sp, fontWeight = FontWeight.${weight})`);
}
lines.push('    }', '}', '');
const output = lines.join('\n');
const destination = path.join(root, 'liquidglass/src/main/java/dev/liquidglass/ios27/Ios27Tokens.kt');
if (process.argv.includes('--check')) {
    if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== output) {
        throw new Error('Generated tokens are stale. Run node tools/generate-ios27-tokens.mjs');
    }
    console.log('Page/list token projection matches all three source hashes.');
} else {
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.writeFileSync(destination, output, 'utf8');
    console.log(path.relative(root, destination));
}
